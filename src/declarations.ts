import { existsSync, readFileSync } from "node:fs"
import { join, relative, resolve, sep } from "node:path"
import { expandHome, getProject } from "./config.ts"
import { flatten } from "./names.ts"
import { availableEnvs, resolveProject } from "./resolve.ts"
import type { Config, Loader, Target } from "./schema.ts"
import type { EnvVar, ScalarType } from "./types.ts"

export const tsHeader = "// Generated by dotgen"

// A target's variables merged across every environment: present in all → required.
export function collectVars(config: Config, name: string, target: string): EnvVar[] {
	const envs = availableEnvs(config, getProject(config, name))
	const vars = new Map<string, EnvVar>()
	for (const env of envs) {
		const values = resolveProject(config, name, env)[target] ?? {}
		for (const entry of flatten(values, [target])) {
			const current = vars.get(entry.name) ?? { name: entry.name, path: entry.path, types: {}, required: false }
			current.types[env] = typeof entry.value as ScalarType
			vars.set(entry.name, current)
		}
	}
	return [...vars.values()]
		.map((item) => ({ ...item, required: Object.keys(item.types).length === envs.length }))
		.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
}

// In a vite target, only what's under `vite: { … }` reaches the browser.
export function isClientVar(item: EnvVar): boolean {
	return item.path[0] === "vite"
}

function members(vars: EnvVar[], indent: string, readonly: boolean): string {
	return vars.map((item) => `${indent}${readonly ? "readonly " : ""}${item.name}${item.required ? "" : "?"}: string`).join("\n")
}

export function renderDeclarations(context: { vars: EnvVar[]; loader: Loader }): string {
	const { vars, loader } = context
	const processEnv = ["\tnamespace NodeJS {", "\t\tinterface ProcessEnv {", members(vars, "\t\t\t", false), "\t\t}", "\t}"]
	const body: Record<Loader, string[]> = {
		bun: ['declare module "bun" {', "\tinterface Env {", members(vars, "\t\t", false), "\t}", "}", "declare global {", ...processEnv, "}"],
		vite: ["declare global {", "\tinterface ImportMetaEnv {", members(vars.filter(isClientVar), "\t\t", true), "\t}", "}"],
		node: ["declare global {", ...processEnv, "}"]
	}
	const lines = [`${tsHeader}. Do not edit.`, "export {}", ...body[loader]].filter((line) => line !== "")
	return `${lines.join("\n")}\n`
}

export function declarationsPath(root: string, target: Target): string {
	return resolve(root, target.dir, target.types ?? "env.d.ts")
}

export function projectRoot(path: string): string {
	return resolve(expandHome(path))
}

// Strips comments and trailing commas from a tsconfig (JSONC) without touching string contents.
function parseJsonc(text: string): unknown {
	const clean = text
		.replace(/("(?:\\.|[^"\\])*")|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, (match, string) => string ?? "")
		.replace(/("(?:\\.|[^"\\])*")|,(\s*[}\]])/g, (match, string, closing) => string ?? closing)
	return JSON.parse(clean)
}

function globToRegExp(pattern: string): RegExp {
	let source = ""
	for (let index = 0; index < pattern.length; index++) {
		const char = pattern[index]!
		if (char === "*" && pattern[index + 1] === "*") {
			source += ".*"
			index++
			if (pattern[index + 1] === "/") index++
		} else if (char === "*") source += "[^/]*"
		else if (char === "?") source += "[^/]"
		else source += char.replace(/[.+^${}()|[\]\\]/g, "\\$&")
	}
	return new RegExp(`^${source}$`)
}

// Approximates TypeScript's `include`/`files`: a pattern without wildcards that names
// a folder includes everything under it. Doesn't follow `extends` or `references`.
export function includedByTsconfig(tsconfigFile: string, file: string): boolean {
	const tsconfig = parseJsonc(readFileSync(tsconfigFile, "utf8")) as { include?: string[]; files?: string[] }
	const base = resolve(tsconfigFile, "..")
	const target = relative(base, file).split(sep).join("/")
	if (!tsconfig.include && !tsconfig.files) return !target.startsWith("../")

	const normalize = (pattern: string) => pattern.replace(/^\.\//, "").replace(/\/$/, "")
	if ((tsconfig.files ?? []).some((pattern) => normalize(pattern) === target)) return true
	return (tsconfig.include ?? []).some((raw) => {
		const pattern = normalize(raw)
		if (pattern === "" || pattern === ".") return !target.startsWith("../")
		if (globToRegExp(pattern).test(target)) return true
		// Folder without wildcards, or pattern without an extension: TS appends `/**/*`.
		return globToRegExp(`${pattern}/**/*`).test(target)
	})
}

// Warns if the target's `tsconfig.json` doesn't include the types file.
export function tsconfigWarning(dir: string, file: string): string | undefined {
	const tsconfigFile = join(dir, "tsconfig.json")
	if (!existsSync(tsconfigFile)) return undefined
	try {
		if (includedByTsconfig(tsconfigFile, file)) return undefined
	} catch {
		return `Couldn't read ${tsconfigFile} to check that it includes ${file}.`
	}
	return `${file} isn't included in ${tsconfigFile}: TypeScript won't see the types.`
}
