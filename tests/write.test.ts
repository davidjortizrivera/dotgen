import { spawnSync } from "node:child_process"
import { mkdtempSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { homedir, tmpdir } from "node:os"
import { join } from "node:path"
import { beforeEach, describe, expect, it } from "vitest"
import { flatten } from "../src/names.ts"
import { display, envHeader, gitignoreWarning, renderEnvFile, tildePath, writeGenerated } from "../src/write.ts"

const entries = flatten({
	database: { server: "db-dev.example.com", password: "abc$defgh123" },
	m3: { dryRun: true },
	backendPort: 3791
})

describe("renderEnvFile", () => {
	it("writes the header, sorts alphabetically, and escapes for the loader", () => {
		const content = renderEnvFile({ entries, loader: "bun", project: "myapp", env: "development", source: join(homedir(), ".config/dotgen/config.ts") })
		expect(content).toBe(
			[
				"# Generated by dotgen from ~/.config/dotgen/config.ts (myapp / development).",
				"# Do not edit: changes are lost when regenerating.",
				'BACKEND_PORT="3791"',
				'DATABASE_PASSWORD="abc\\$defgh123"',
				'DATABASE_SERVER="db-dev.example.com"',
				'M3_DRY_RUN="true"',
				""
			].join("\n")
		)
	})

	it("uses node escaping", () => {
		const content = renderEnvFile({ entries, loader: "node", project: "p", env: "e", source: "/c.ts" })
		expect(content).toContain('DATABASE_PASSWORD="abc$defgh123"')
	})
})

describe("display", () => {
	it.each([
		["DATABASE_PASSWORD", "abc$defgh123", "set (12 chars)"],
		["CLIENT_SECRET", "x", "set (1 chars)"],
		["API_TOKEN", "abcd", "set (4 chars)"],
		["API_KEY", "abcd", "set (4 chars)"],
		["DATABASE_SERVER", "db", '"db"'],
		["TRANSPORT_URI", "smtp://user:clave@smtp.example.com:587", "set (38 chars)"],
		["DATABASE_CONNECTION_URI", "Server=x", "set (8 chars)"],
		["SMTP_PASS", "x", "set (1 chars)"],
		["PUBLIC_URL", "https://example.com/a@b", '"https://example.com/a@b"'],
		["PORT", 3791, '"3791"']
	])("%s", (name, value, expected) => {
		expect(display(name, value)).toBe(expected)
	})
})

describe("tildePath", () => {
	it("abbreviates only paths inside home", () => {
		expect(tildePath(join(homedir(), "a"))).toBe("~/a")
		expect(tildePath(`${homedir()}x/a`)).toBe(`${homedir()}x/a`)
	})
})

describe("writeGenerated", () => {
	let dir: string
	let file: string
	const options = { header: envHeader, mode: 0o600 }
	const content = `${envHeader} from x.\nA="1"\n`

	beforeEach(() => {
		dir = mkdtempSync(join(tmpdir(), "dotgen-write-"))
		file = join(dir, ".env.development")
	})

	it("creates the file with 600 permissions", () => {
		expect(writeGenerated(file, content, options)).toEqual({ file, status: "created", written: true })
		expect(readFileSync(file, "utf8")).toBe(content)
		expect(statSync(file).mode & 0o777).toBe(0o600)
	})

	it("doesn't rewrite an unchanged file, but fixes its permissions", () => {
		writeFileSync(file, content, { mode: 0o644 })
		expect(writeGenerated(file, content, options)).toEqual({ file, status: "unchanged", written: false })
		expect(statSync(file).mode & 0o777).toBe(0o600)
	})

	it("updates a generated file", () => {
		writeGenerated(file, content, options)
		expect(writeGenerated(file, `${content}B="2"\n`, options).status).toBe("updated")
	})

	it("still recognizes files generated by earlier versions", () => {
		writeFileSync(file, '# Generado por dotgen desde x.\nA="1"\n')
		expect(writeGenerated(file, content, options).status).toBe("updated")
	})

	it("doesn't overwrite a foreign file without --force", () => {
		writeFileSync(file, 'A="manual"\n')
		expect(() => writeGenerated(file, content, options)).toThrow(/wasn't generated by dotgen. Use --force/)
		expect(readFileSync(file, "utf8")).toBe('A="manual"\n')
		expect(writeGenerated(file, content, { ...options, force: true }).status).toBe("updated")
		expect(readFileSync(file, "utf8")).toBe(content)
	})

	it("--dry-run validates but doesn't write", () => {
		writeFileSync(file, 'A="manual"\n')
		expect(() => writeGenerated(file, content, { ...options, dryRun: true })).toThrow(/--force/)
		const other = join(dir, "new")
		expect(writeGenerated(other, content, { ...options, dryRun: true })).toEqual({ file: other, status: "created", written: false })
		expect(() => statSync(other)).toThrow()
	})
})

describe("gitignoreWarning", () => {
	it("warns when not ignored, and stays quiet when ignored or outside a repo", () => {
		const dir = mkdtempSync(join(tmpdir(), "dotgen-git-"))
		const file = join(dir, ".env.development")
		expect(gitignoreWarning(file)).toBeUndefined()

		spawnSync("git", ["init", "-q"], { cwd: dir })
		expect(gitignoreWarning(file)).toMatch(/isn't in .gitignore/)

		writeFileSync(join(dir, ".gitignore"), ".env.*\n")
		expect(gitignoreWarning(file)).toBeUndefined()
	})
})
