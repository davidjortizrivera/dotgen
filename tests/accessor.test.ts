import { describe, expect, it } from "vitest"
import { renderAccessor } from "../src/accessor.ts"
import type { EnvVar } from "../src/types.ts"

function item(path: string[], name: string, types: EnvVar["types"], required = true): EnvVar {
	return { path, name, types, required }
}

const vars: EnvVar[] = [
	item(["database", "port"], "DATABASE_PORT", { development: "number", production: "number" }),
	item(["database", "server"], "DATABASE_SERVER", { development: "string", production: "string" }),
	item(["m3", "dryRun"], "M3_DRY_RUN", { development: "boolean" }, false),
	item(["timeout"], "TIMEOUT", { development: "number" }, false),
	item(["label"], "LABEL", { development: "string" }, false),
	item(["NODE_ENV"], "NODE_ENV", { development: "string", production: "string" }),
	item(["vite", "debug"], "VITE_DEBUG", { development: "boolean", production: "boolean" })
]

describe("renderAccessor", () => {
	it("bun: nested object with type conversion", () => {
		expect(renderAccessor({ vars, loader: "bun", prefix: "projects.myapp.backend" })).toBe(
			[
				"// Generated by dotgen. Do not edit.",
				"export const env = {",
				"\tNODE_ENV: Bun.env.NODE_ENV!,",
				"\tdatabase: {",
				"\t\tport: Number(Bun.env.DATABASE_PORT),",
				"\t\tserver: Bun.env.DATABASE_SERVER!",
				"\t},",
				"\tlabel: Bun.env.LABEL,",
				"\tm3: {",
				'\t\tdryRun: Bun.env.M3_DRY_RUN === undefined ? undefined : Bun.env.M3_DRY_RUN === "true"',
				"\t},",
				"\ttimeout: Bun.env.TIMEOUT === undefined ? undefined : Number(Bun.env.TIMEOUT),",
				"\tvite: {",
				'\t\tdebug: Bun.env.VITE_DEBUG === "true"',
				"\t}",
				"}",
				""
			].join("\n")
		)
	})

	it("vite: only vite.* from import.meta.env", () => {
		expect(renderAccessor({ vars, loader: "vite", prefix: "p" })).toBe(
			["// Generated by dotgen. Do not edit.", "export const env = {", "\tvite: {", '\t\tdebug: import.meta.env.VITE_DEBUG === "true"', "\t}", "}", ""].join("\n")
		)
	})

	it("node: reads process.env", () => {
		expect(renderAccessor({ vars, loader: "node", prefix: "p" })).toContain("port: Number(process.env.DATABASE_PORT)")
	})

	it("empty object", () => {
		expect(renderAccessor({ vars: [], loader: "bun", prefix: "p" })).toBe("// Generated by dotgen. Do not edit.\nexport const env = {}\n")
	})

	it("fails when types differ across environments", () => {
		const mixed = [item(["database", "port"], "DATABASE_PORT", { development: "number", production: "string" })]
		expect(() => renderAccessor({ vars: mixed, loader: "bun", prefix: "projects.myapp.backend" })).toThrow(
			"projects.myapp.backend.database.port: has different types across environments (number in development, string in production)."
		)
	})
})
