import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { describe, expect, it } from "vitest"
import { parseConfig } from "../src/config.ts"
import { collectVars, declarationsPath, includedByTsconfig, renderDeclarations, tsconfigWarning } from "../src/declarations.ts"
import { defineConfig } from "../src/index.ts"

const config = parseConfig(
	defineConfig({
		shared: {
			development: { backend: { database: { server: "db-dev", port: 1433 } } },
			production: { backend: { database: { server: "db", port: 1433 } } }
		},
		projects: {
			myapp: {
				path: "/work/myapp",
				ports: { backend: 3791, frontend: 5791 },
				targets: {
					backend: { dir: "apps/backend", loader: "bun" },
					frontend: { dir: "apps/frontend", loader: "vite", accessor: true, types: "src/env.d.ts" }
				},
				derive: (context) => {
					const { port } = context
					return { frontend: { frontendPort: port.frontend ?? 0, vite: { backendBaseUrl: `https://localhost:${port.backend}` } } }
				},
				development: {
					backend: { database: { password: "abc$defgh123" }, m3: { dryRun: true } },
					frontend: { vite: { debug: true } }
				},
				production: { backend: { database: { password: "x" } } }
			}
		}
	})
)

describe("collectVars", () => {
	it("merges environments and marks optional variables", () => {
		const vars = collectVars(config, "myapp", "backend")
		expect(vars.map((item) => [item.name, item.required])).toEqual([
			["DATABASE_PASSWORD", true],
			["DATABASE_PORT", true],
			["DATABASE_SERVER", true],
			["M3_DRY_RUN", false]
		])
		expect(vars[1]!.types).toEqual({ development: "number", production: "number" })
	})
})

describe("renderDeclarations", () => {
	it("bun: bun module and ProcessEnv", () => {
		expect(renderDeclarations({ vars: collectVars(config, "myapp", "backend"), loader: "bun" })).toBe(
			[
				"// Generated by dotgen. Do not edit.",
				"export {}",
				'declare module "bun" {',
				"\tinterface Env {",
				"\t\tDATABASE_PASSWORD: string",
				"\t\tDATABASE_PORT: string",
				"\t\tDATABASE_SERVER: string",
				"\t\tM3_DRY_RUN?: string",
				"\t}",
				"}",
				"declare global {",
				"\tnamespace NodeJS {",
				"\t\tinterface ProcessEnv {",
				"\t\t\tDATABASE_PASSWORD: string",
				"\t\t\tDATABASE_PORT: string",
				"\t\t\tDATABASE_SERVER: string",
				"\t\t\tM3_DRY_RUN?: string",
				"\t\t}",
				"\t}",
				"}",
				""
			].join("\n")
		)
	})

	it("vite: ImportMetaEnv with only VITE_*", () => {
		expect(renderDeclarations({ vars: collectVars(config, "myapp", "frontend"), loader: "vite" })).toBe(
			[
				"// Generated by dotgen. Do not edit.",
				"export {}",
				"declare global {",
				"\tinterface ImportMetaEnv {",
				"\t\treadonly VITE_BACKEND_BASE_URL: string",
				"\t\treadonly VITE_DEBUG?: string",
				"\t}",
				"}",
				""
			].join("\n")
		)
	})

	it("node: ProcessEnv only", () => {
		const content = renderDeclarations({ vars: collectVars(config, "myapp", "backend"), loader: "node" })
		expect(content).not.toContain('"bun"')
		expect(content).toContain("\t\t\tM3_DRY_RUN?: string")
	})

	it("includes no values", () => {
		expect(renderDeclarations({ vars: collectVars(config, "myapp", "backend"), loader: "bun" })).not.toContain("abc")
	})
})

describe("declarationsPath", () => {
	it("uses env.d.ts or the target's `types`", () => {
		const project = config.projects.myapp!
		expect(declarationsPath("/work/myapp", project.targets.backend!)).toBe("/work/myapp/apps/backend/env.d.ts")
		expect(declarationsPath("/work/myapp", project.targets.frontend!)).toBe("/work/myapp/apps/frontend/src/env.d.ts")
	})
})

describe("tsconfig", () => {
	function setup(tsconfig: string) {
		const dir = mkdtempSync(join(tmpdir(), "dotgen-tsconfig-"))
		mkdirSync(join(dir, "src"))
		writeFileSync(join(dir, "tsconfig.json"), tsconfig)
		return dir
	}

	it.each([
		["no include", "{}", "env.d.ts", true],
		["include with comments and a trailing comma", '{ // x\n "include": ["src/**/*.ts", "env.d.ts",] /* y */ }', "env.d.ts", true],
		["folder include", '{ "include": ["src"] }', "src/env.d.ts", true],
		["glob include", '{ "include": ["src/**/*"] }', "src/env.d.ts", true],
		["include that doesn't cover it", '{ "include": ["src"] }', "env.d.ts", false],
		["files", '{ "files": ["./env.d.ts"] }', "env.d.ts", true],
		["string with //", '{ "include": ["src"], "x": "http://a" }', "env.d.ts", false]
	])("%s", (label, tsconfig, file, expected) => {
		const dir = setup(tsconfig)
		expect(includedByTsconfig(join(dir, "tsconfig.json"), join(dir, file))).toBe(expected)
	})

	it("tsconfigWarning warns only when it isn't included", () => {
		const dir = setup('{ "include": ["src"] }')
		expect(tsconfigWarning(dir, join(dir, "src/env.d.ts"))).toBeUndefined()
		expect(tsconfigWarning(dir, join(dir, "env.d.ts"))).toMatch(/isn't included/)
		expect(tsconfigWarning(join(dir, "src"), join(dir, "env.d.ts"))).toBeUndefined()
	})
})
